"""The committed benchmark caveat must match the harness computation.

The dashboard caveat string is rendered from diagnostics/headlines_output.json,
which must be regenerated by `python diagnostics/reproduce_headlines.py
--write-json diagnostics/headlines_output.json`. These tests recompute the
template-family statistics from the committed CSV and fail if the committed
JSON was hand-edited (including hardcoding "0" shared families).
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HARNESS_PATH = ROOT / "diagnostics" / "reproduce_headlines.py"
HEADLINES_OUTPUT_PATH = ROOT / "diagnostics" / "headlines_output.json"


def _load_harness():
    spec = importlib.util.spec_from_file_location("reproduce_headlines", HARNESS_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_committed_caveat_matches_harness_computation() -> None:
    harness = _load_harness()
    texts, labels = harness.read_training_rows()
    computed = {
        "csv_records": len(texts),
        **harness.template_family_stats(texts, labels),
    }
    committed = json.loads(HEADLINES_OUTPUT_PATH.read_text(encoding="utf-8"))["caveat"]
    assert committed == computed


def test_caveat_string_matches_computed_counts() -> None:
    harness = _load_harness()
    texts, labels = harness.read_training_rows()
    stats = harness.template_family_stats(texts, labels)
    caveat = {
        "csv_records": len(texts),
        **stats,
    }
    expected = (
        f"measured on the committed {caveat['csv_records']}-row set: "
        f"{caveat['template_families']} template families, "
        f"{caveat['families_shared_between_classes']} shared between classes "
        "→ not a generalization measurement"
    )
    # When no family is shared between classes the caveat must say exactly that,
    # with the computed counts — never a hardcoded "0".
    if caveat["families_shared_between_classes"] == 0:
        assert "0 shared between classes" in expected
        assert f"{caveat['template_families']} template families" in expected
